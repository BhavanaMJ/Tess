import 'dart:convert';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import '../controllers/garment_import_controller.dart';
import '../theme/wardrobe_theme.dart';

class ImportStage3Json extends StatefulWidget {
  final GarmentImportController controller;

  const ImportStage3Json({
    super.key,
    required this.controller,
  });

  @override
  State<ImportStage3Json> createState() => _ImportStage3JsonState();
}

class _ImportStage3JsonState extends State<ImportStage3Json> {
  late TextEditingController _textController;

  @override
  void initState() {
    super.initState();
    _textController = TextEditingController(text: widget.controller.rawJson);
  }

  @override
  void didUpdateWidget(covariant ImportStage3Json oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (widget.controller.rawJson != _textController.text) {
      _textController.text = widget.controller.rawJson;
    }
  }

  @override
  void dispose() {
    _textController.dispose();
    super.dispose();
  }

  Future<void> _pasteFromClipboard() async {
    final data = await Clipboard.getData(Clipboard.kTextPlain);
    if (data?.text != null && data!.text!.isNotEmpty) {
      setState(() {
        _textController.text = data.text!;
      });
      widget.controller.setRawJson(data.text!);
      widget.controller.validateMetadata();
    }
  }

  void _formatJson() {
    try {
      final decoded = jsonDecode(_textController.text);
      final pretty = const JsonEncoder.withIndent('  ').convert(decoded);
      setState(() {
        _textController.text = pretty;
      });
      widget.controller.setRawJson(pretty);
    } catch (_) {}
  }

  @override
  Widget build(BuildContext context) {
    final isValidating = widget.controller.isValidating;
    final errors = widget.controller.validationErrors;
    final warnings = widget.controller.validationWarnings;
    final isValid = widget.controller.isMetadataValid;

    return SingleChildScrollView(
      padding: const EdgeInsets.all(16.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          // Header Banner
          Container(
            padding: const EdgeInsets.all(14.0),
            decoration: BoxDecoration(
              color: WardrobeTheme.spatialSurface,
              borderRadius: BorderRadius.circular(12),
              border: Border.all(color: WardrobeTheme.borderViolet),
            ),
            child: Row(
              children: [
                Container(
                  width: 36,
                  height: 36,
                  decoration: BoxDecoration(
                    color: WardrobeTheme.electricViolet.withValues(alpha: 0.2),
                    shape: BoxShape.circle,
                  ),
                  child: Icon(Icons.code_rounded,
                      color: WardrobeTheme.softViolet, size: 20),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        'Import Metadata JSON (Schema 1.1)',
                        style: TextStyle(
                          fontSize: 13,
                          fontWeight: FontWeight.w700,
                          color: WardrobeTheme.textPrimary,
                        ),
                      ),
                      const SizedBox(height: 2),
                      Text(
                        'Paste the JSON generated by ChatGPT. TESS will validate all garment attributes before review.',
                        style: TextStyle(
                          fontSize: 11,
                          color: WardrobeTheme.textSecondary,
                          height: 1.35,
                        ),
                      ),
                    ],
                  ),
                ),
              ],
            ),
          ),

          const SizedBox(height: 16),

          // Actions Row (Paste, Format, Clear)
          Row(
            children: [
              ElevatedButton.icon(
                onPressed: _pasteFromClipboard,
                icon: const Icon(Icons.content_paste_rounded, size: 15),
                label: const Text('Paste JSON'),
                style: ElevatedButton.styleFrom(
                  backgroundColor: WardrobeTheme.electricViolet,
                  foregroundColor: Colors.white,
                  padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
                  textStyle: const TextStyle(fontSize: 12, fontWeight: FontWeight.w700),
                ),
              ),
              const SizedBox(width: 8),
              OutlinedButton.icon(
                onPressed: _textController.text.isNotEmpty ? _formatJson : null,
                icon: const Icon(Icons.auto_fix_high_rounded, size: 14),
                label: const Text('Format'),
                style: OutlinedButton.styleFrom(
                  foregroundColor: WardrobeTheme.electricCyan,
                  side: BorderSide(color: WardrobeTheme.border),
                  padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 8),
                  textStyle: const TextStyle(fontSize: 12),
                ),
              ),
              const Spacer(),
              if (_textController.text.isNotEmpty)
                TextButton.icon(
                  onPressed: () {
                    setState(() {
                      _textController.clear();
                    });
                    widget.controller.clearJson();
                  },
                  icon: Icon(Icons.clear_rounded, size: 14, color: WardrobeTheme.statusCritical),
                  label: Text('Clear', style: TextStyle(color: WardrobeTheme.statusCritical, fontSize: 12)),
                ),
            ],
          ),

          const SizedBox(height: 10),

          // JSON Editor Text Area
          Container(
            decoration: BoxDecoration(
              color: WardrobeTheme.spatialSurface,
              borderRadius: BorderRadius.circular(12),
              border: Border.all(
                color: errors.isNotEmpty
                    ? WardrobeTheme.statusCritical
                    : isValid
                        ? WardrobeTheme.statusSuccess
                        : WardrobeTheme.borderSubtle,
                width: errors.isNotEmpty || isValid ? 1.5 : 1.0,
              ),
            ),
            child: TextField(
              controller: _textController,
              maxLines: 12,
              onChanged: (text) {
                widget.controller.setRawJson(text);
              },
              style: const TextStyle(
                fontFamily: 'monospace',
                fontSize: 11.5,
                color: Color(0xFFE2E8F0),
                height: 1.4,
              ),
              decoration: InputDecoration(
                contentPadding: const EdgeInsets.all(12),
                hintText: '{\n  "schema_version": "1.1",\n  "record_type": "garment",\n  "identity": {\n    "garment_name": "...",\n    "category": "..."\n  } ...\n}',
                hintStyle: TextStyle(
                  fontFamily: 'monospace',
                  fontSize: 11,
                  color: WardrobeTheme.textMuted.withValues(alpha: 0.5),
                ),
                border: InputBorder.none,
              ),
            ),
          ),

          const SizedBox(height: 12),

          // Validate Button
          ElevatedButton.icon(
            onPressed: isValidating || _textController.text.trim().isEmpty
                ? null
                : () => widget.controller.validateMetadata(),
            icon: isValidating
                ? const SizedBox(
                    width: 16,
                    height: 16,
                    child: CircularProgressIndicator(strokeWidth: 2, color: Colors.white),
                  )
                : const Icon(Icons.check_circle_outline_rounded, size: 18),
            label: Text(
              isValidating ? 'Validating Metadata...' : 'Validate Schema 1.1',
              style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w700),
            ),
            style: ElevatedButton.styleFrom(
              backgroundColor: WardrobeTheme.electricCyan,
              foregroundColor: Colors.black,
              disabledBackgroundColor: WardrobeTheme.spatialSurface,
              padding: const EdgeInsets.symmetric(vertical: 12),
              shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
            ),
          ),

          // Validation Errors Box
          if (errors.isNotEmpty) ...[
            const SizedBox(height: 14),
            Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: WardrobeTheme.statusCritical.withValues(alpha: 0.12),
                borderRadius: BorderRadius.circular(10),
                border: Border.all(color: WardrobeTheme.statusCritical.withValues(alpha: 0.3)),
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    children: [
                      Icon(Icons.error_outline_rounded,
                          size: 16, color: WardrobeTheme.statusCritical),
                      const SizedBox(width: 6),
                      Text(
                        'Validation Issues Found',
                        style: TextStyle(
                          fontSize: 12,
                          fontWeight: FontWeight.w800,
                          color: WardrobeTheme.statusCritical,
                        ),
                      ),
                    ],
                  ),
                  const SizedBox(height: 8),
                  ...errors.map((e) => Padding(
                        padding: const EdgeInsets.only(bottom: 4.0),
                        child: Text(
                          '• $e',
                          style: TextStyle(fontSize: 11, color: WardrobeTheme.textSecondary),
                        ),
                      )),
                ],
              ),
            ),
          ],

          // Warnings Box
          if (warnings.isNotEmpty) ...[
            const SizedBox(height: 10),
            Container(
              padding: const EdgeInsets.all(10),
              decoration: BoxDecoration(
                color: WardrobeTheme.statusWarning.withValues(alpha: 0.1),
                borderRadius: BorderRadius.circular(8),
                border: Border.all(color: WardrobeTheme.statusWarning.withValues(alpha: 0.25)),
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: warnings.map((w) => Padding(
                  padding: const EdgeInsets.symmetric(vertical: 2.0),
                  child: Text(
                    'Notice: $w',
                    style: TextStyle(fontSize: 10.5, color: WardrobeTheme.textSecondary),
                  ),
                )).toList(),
              ),
            ),
          ],

          // Validation Success Banner
          if (isValid) ...[
            const SizedBox(height: 14),
            Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: WardrobeTheme.statusSuccess.withValues(alpha: 0.15),
                borderRadius: BorderRadius.circular(10),
                border: Border.all(color: WardrobeTheme.statusSuccess.withValues(alpha: 0.3)),
              ),
              child: Row(
                children: [
                  Icon(Icons.verified_rounded, size: 20, color: WardrobeTheme.statusSuccess),
                  const SizedBox(width: 10),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text(
                          'Schema Version 1.1 Verified',
                          style: TextStyle(
                            fontSize: 12,
                            fontWeight: FontWeight.w800,
                            color: WardrobeTheme.statusSuccess,
                          ),
                        ),
                        Text(
                          'Garment: ${widget.controller.metadata?.identity.garmentName} • Category: ${widget.controller.metadata?.identity.category}',
                          style: TextStyle(fontSize: 11, color: WardrobeTheme.textPrimary),
                        ),
                      ],
                    ),
                  ),
                ],
              ),
            ),
          ],
        ],
      ),
    );
  }
}
