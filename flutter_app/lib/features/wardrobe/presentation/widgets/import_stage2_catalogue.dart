import 'dart:typed_data';
import 'package:flutter/material.dart';
import 'package:image_picker/image_picker.dart';
import '../controllers/garment_import_controller.dart';
import '../theme/wardrobe_theme.dart';

class ImportStage2Catalogue extends StatelessWidget {
  final GarmentImportController controller;

  const ImportStage2Catalogue({
    super.key,
    required this.controller,
  });

  @override
  Widget build(BuildContext context) {
    final hasImage = controller.catalogueImageBytes != null;

    return SingleChildScrollView(
      padding: const EdgeInsets.all(16.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          // Banner explaining ChatGPT Studio Image
          Container(
            padding: const EdgeInsets.all(14.0),
            decoration: BoxDecoration(
              color: WardrobeTheme.spatialSurface,
              borderRadius: BorderRadius.circular(12),
              border: Border.all(color: WardrobeTheme.borderViolet),
            ),
            child: Row(
              children: [
                Container(
                  width: 36,
                  height: 36,
                  decoration: BoxDecoration(
                    color: WardrobeTheme.electricViolet.withValues(alpha: 0.2),
                    shape: BoxShape.circle,
                  ),
                  child: Icon(Icons.checkroom_rounded,
                      color: WardrobeTheme.softViolet, size: 20),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        'Import Studio Catalogue Photograph',
                        style: TextStyle(
                          fontSize: 13,
                          fontWeight: FontWeight.w700,
                          color: WardrobeTheme.textPrimary,
                        ),
                      ),
                      const SizedBox(height: 2),
                      Text(
                        'Upload the clean, studio-style catalogue image generated by ChatGPT. This will be the high-resolution primary photo in your wardrobe.',
                        style: TextStyle(
                          fontSize: 11,
                          color: WardrobeTheme.textSecondary,
                          height: 1.35,
                        ),
                      ),
                    ],
                  ),
                ),
              ],
            ),
          ),

          const SizedBox(height: 20),

          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Text(
                'STUDIO CATALOGUE IMAGE (MANDATORY)',
                style: TextStyle(
                  fontSize: 11,
                  fontWeight: FontWeight.w800,
                  letterSpacing: 0.8,
                  color: WardrobeTheme.textMuted,
                ),
              ),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                decoration: BoxDecoration(
                  color: hasImage
                      ? WardrobeTheme.statusSuccess.withValues(alpha: 0.15)
                      : WardrobeTheme.statusWarning.withValues(alpha: 0.15),
                  borderRadius: BorderRadius.circular(4),
                ),
                child: Text(
                  hasImage ? 'ATTACHED' : 'REQUIRED',
                  style: TextStyle(
                    fontSize: 10,
                    fontWeight: FontWeight.w800,
                    color: hasImage
                        ? WardrobeTheme.statusSuccess
                        : WardrobeTheme.statusWarning,
                  ),
                ),
              ),
            ],
          ),
          const SizedBox(height: 8),

          if (hasImage) ...[
            Container(
              height: 320,
              decoration: BoxDecoration(
                color: WardrobeTheme.studioBackground, // Clean white studio background
                borderRadius: BorderRadius.circular(14),
                border: Border.all(color: WardrobeTheme.borderViolet, width: 1.5),
                boxShadow: [
                  BoxShadow(
                    color: Colors.black.withValues(alpha: 0.3),
                    blurRadius: 10,
                    offset: const Offset(0, 4),
                  ),
                ],
              ),
              clipBehavior: Clip.antiAlias,
              child: Stack(
                alignment: Alignment.center,
                children: [
                  Image.memory(
                    Uint8List.fromList(controller.catalogueImageBytes!),
                    fit: BoxFit.contain,
                    width: double.infinity,
                    height: 320,
                  ),
                  Positioned(
                    top: 10,
                    right: 10,
                    child: Container(
                      decoration: BoxDecoration(
                        color: Colors.black.withValues(alpha: 0.65),
                        shape: BoxShape.circle,
                      ),
                      child: IconButton(
                        icon: const Icon(Icons.close, color: Colors.white, size: 18),
                        tooltip: 'Remove Image',
                        onPressed: () => controller.removeCatalogueImage(),
                      ),
                    ),
                  ),
                  Positioned(
                    bottom: 10,
                    left: 10,
                    child: Container(
                      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                      decoration: BoxDecoration(
                        color: Colors.black.withValues(alpha: 0.75),
                        borderRadius: BorderRadius.circular(6),
                      ),
                      child: Row(
                        mainAxisSize: MainAxisSize.min,
                        children: [
                          Icon(Icons.verified, size: 12, color: WardrobeTheme.statusSuccess),
                          const SizedBox(width: 4),
                          const Text(
                            'Studio Quality Preview',
                            style: TextStyle(fontSize: 10, color: Colors.white, fontWeight: FontWeight.w600),
                          ),
                        ],
                      ),
                    ),
                  ),
                ],
              ),
            ),
            const SizedBox(height: 12),
            Row(
              children: [
                Expanded(
                  child: OutlinedButton.icon(
                    onPressed: () => controller.pickCatalogueImage(ImageSource.gallery),
                    icon: const Icon(Icons.photo_library_outlined, size: 16),
                    label: const Text('Replace Catalogue Photo'),
                    style: OutlinedButton.styleFrom(
                      foregroundColor: WardrobeTheme.textSecondary,
                      side: BorderSide(color: WardrobeTheme.border),
                    ),
                  ),
                ),
              ],
            ),
          ] else ...[
            Container(
              padding: const EdgeInsets.symmetric(vertical: 48, horizontal: 20),
              decoration: BoxDecoration(
                color: WardrobeTheme.spatialSurface,
                borderRadius: BorderRadius.circular(14),
                border: Border.all(
                  color: WardrobeTheme.borderViolet.withValues(alpha: 0.4),
                  width: 1.5,
                ),
              ),
              child: Column(
                children: [
                  Container(
                    width: 56,
                    height: 56,
                    decoration: BoxDecoration(
                      color: WardrobeTheme.electricViolet.withValues(alpha: 0.15),
                      shape: BoxShape.circle,
                    ),
                    child: Icon(Icons.cloud_upload_outlined,
                        size: 30, color: WardrobeTheme.electricViolet),
                  ),
                  const SizedBox(height: 14),
                  Text(
                    'Upload ChatGPT Catalogue Image',
                    style: TextStyle(
                      fontSize: 15,
                      fontWeight: FontWeight.w700,
                      color: WardrobeTheme.textPrimary,
                    ),
                  ),
                  const SizedBox(height: 6),
                  Text(
                    'Save the studio-style photograph generated by ChatGPT to your device, then upload it here.',
                    textAlign: TextAlign.center,
                    style: TextStyle(fontSize: 12, color: WardrobeTheme.textSecondary, height: 1.3),
                  ),
                  const SizedBox(height: 20),
                  ElevatedButton.icon(
                    onPressed: () => controller.pickCatalogueImage(ImageSource.gallery),
                    icon: const Icon(Icons.file_upload_outlined, size: 18),
                    label: const Text('Select from Device Gallery'),
                    style: ElevatedButton.styleFrom(
                      backgroundColor: WardrobeTheme.electricViolet,
                      foregroundColor: Colors.white,
                      padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 12),
                      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
                    ),
                  ),
                  const SizedBox(height: 8),
                  Text(
                    'Supported formats: JPG, JPEG, PNG, WEBP (Max 15MB)',
                    style: TextStyle(fontSize: 10, color: WardrobeTheme.textMuted),
                  ),
                ],
              ),
            ),
          ],
        ],
      ),
    );
  }
}
